"""
Estimate the geographic position of cattle detected in drone images.

Version 1 - FLAT TERRAIN

This script does NOT use the DEM yet.

Method
------
For each YOLO bounding box:

1. Compute the center of the bounding box in image pixels.
2. Convert the pixel position into a camera ray.
3. Transform the camera ray according to the DJI gimbal orientation.
4. Intersect the ray with a horizontal ground plane.
5. Express the resulting point in EPSG:29192.
6. Transform the point to WGS84 (EPSG:4326).
7. Save the estimated cattle position as GeoJSON.

Important
---------
This is a geometric approximation.

The following assumptions are made:

- The terrain is locally flat.
- The bounding-box center represents the animal position.
- The camera is approximately calibrated.
- Lens distortion is ignored.
- The image principal point is the image center.
- The DJI gimbal angles are interpreted according to the
  coordinate convention documented in this script.

The goal of this first version is to validate the geometry.
Terrain/DEM correction will be implemented separately.
"""

