# ============================================================================
# COORDINATE REFERENCE SYSTEMS
# ============================================================================

# Metric CRS used for geometric calculations.
#
# EPSG:29192
# SAD69 / UTM zone 22S
#
# Coordinates are expressed in metres.
METRIC_CRS = "EPSG:29192"

# Geographic CRS used for the final GeoJSON.
#
# EPSG:4326
# WGS 84
#
# Coordinates are:
#   longitude, latitude
GEOGRAPHIC_CRS = "EPSG:4326"


# Transformer from WGS84 geographic coordinates to the metric CRS.
#
# always_xy=True is important:
#
#   input  = longitude, latitude
#   output = easting, northing
#
# Without always_xy=True, pyproj may follow the CRS axis-order
# convention and potentially return latitude/longitude in an
# unexpected order.
WGS84_TO_METRIC = Transformer.from_crs(
    GEOGRAPHIC_CRS,
    METRIC_CRS,
    always_xy=True,
)


# Transformer from the metric CRS back to WGS84.
#
# This is used only after the geometric calculation is finished.
METRIC_TO_WGS84 = Transformer.from_crs(
    METRIC_CRS,
    GEOGRAPHIC_CRS,
    always_xy=True,
)


# ============================================================================
# CAMERA PARAMETERS
# ============================================================================

# DJI Air 3S image dimensions in the current dataset.
#
# We will actually read the dimensions from the metadata for every image,
# but these constants document the expected camera configuration.
DEFAULT_IMAGE_WIDTH = 4096
DEFAULT_IMAGE_HEIGHT = 3072


# Horizontal field of view stored in the metadata.
#
# For the current dataset:
#
#     FOV ≈ 73.74 degrees
#
# We use the horizontal FOV to calculate the horizontal focal length
# in pixels.
#
# This is preferable to hard-coding a focal length in pixels because
# the focal length in millimetres alone is not enough to determine
# the image geometry without knowing the sensor dimensions.
#
# Formula:
#
#             image_width / 2
#     fx = -------------------------
#              tan(FOV / 2)
#
# fx is therefore expressed in pixels.
def focal_length_pixels(
    image_width: int,
    horizontal_fov_deg: float,
) -> float:
    """
    Calculate horizontal focal length in pixels.

    Parameters
    ----------
    image_width:
        Image width in pixels.

    horizontal_fov_deg:
        Horizontal field of view in degrees.

    Returns
    -------
    float
        Focal length in pixels.
    """

    fov_rad = math.radians(horizontal_fov_deg)

    return (
        (image_width / 2.0)
        / math.tan(fov_rad / 2.0)
    )


# ============================================================================
# YOLO ANNOTATION
# ============================================================================

def read_yolo_annotations(
    annotation_file: Path,
) -> list[dict[str, float]]:
    """
    Read a YOLO annotation file.

    Each line has the form:

        class_id x_center y_center width height

    All geometric values are normalized to [0, 1].

    Example:

        0 0.554750 0.688599 0.012034 0.019131

    Returns
    -------
    list of dictionaries
        One dictionary per detected object.
    """

    annotations = []

    with annotation_file.open("r", encoding="utf-8") as f:

        for line_number, line in enumerate(f, start=1):

            line = line.strip()

            if not line:
                continue

            values = line.split()

            if len(values) != 5:
                raise ValueError(
                    f"Invalid YOLO annotation in {annotation_file} "
                    f"line {line_number}: {line}"
                )

            class_id = int(values[0])

            x_center = float(values[1])
            y_center = float(values[2])
            width = float(values[3])
            height = float(values[4])

            annotations.append(
                {
                    "class_id": class_id,
                    "x_center": x_center,
                    "y_center": y_center,
                    "width": width,
                    "height": height,
                }
            )

    return annotations


# ============================================================================
# PIXEL COORDINATES
# ============================================================================

def yolo_to_pixel(
    annotation: dict[str, float],
    image_width: int,
    image_height: int,
) -> tuple[float, float]:
    """
    Convert the normalized YOLO bounding-box center to pixel coordinates.

    YOLO coordinates are normalized:

        x_center = pixel_x / image_width
        y_center = pixel_y / image_height

    Therefore:

        pixel_x = x_center * image_width
        pixel_y = y_center * image_height

    The returned point is the center of the bounding box.
    """

    pixel_x = annotation["x_center"] * image_width
    pixel_y = annotation["y_center"] * image_height

    return pixel_x, pixel_y


# ============================================================================
# CAMERA RAY
# ============================================================================

def pixel_to_camera_ray(
    pixel_x: float,
    pixel_y: float,
    image_width: int,
    image_height: int,
    fx: float,
    fy: float,
) -> np.ndarray:
    """
    Convert an image pixel into a normalized camera ray.

    Camera coordinate system used here:

                    forward
                       Z
                       ^
                       |
                       |
                       +------> X right
                      /
                     /
                    Y down

    The optical axis is +Z.

    The principal point is assumed to be the image center:

        cx = image_width  / 2
        cy = image_height / 2

    Pinhole camera model:

        x = (u - cx) / fx
        y = (v - cy) / fy
        z = 1

    where:

        u = image x coordinate
        v = image y coordinate
        fx = focal length in pixels in X
        fy = focal length in pixels in Y

    The vector is normalized so that its length is 1.

    Returns
    -------
    numpy.ndarray
        [x, y, z] camera ray.
    """

    cx = image_width / 2.0
    cy = image_height / 2.0

    x = (pixel_x - cx) / fx
    y = (pixel_y - cy) / fy

    ray = np.array(
        [x, y, 1.0],
        dtype=float,
    )

    # Normalize the vector.
    ray /= np.linalg.norm(ray)

    return ray


# ============================================================================
# CAMERA ORIENTATION
# ============================================================================

def normalize(vector: np.ndarray) -> np.ndarray:
    """Return a normalized vector."""

    length = np.linalg.norm(vector)

    if length == 0:
        raise ValueError("Cannot normalize a zero-length vector.")

    return vector / length


def camera_ray_to_ned(
    ray_camera: np.ndarray,
    gimbal_yaw_deg: float,
    gimbal_pitch_deg: float,
    gimbal_roll_deg: float,
) -> np.ndarray:
    """
    Transform a camera ray into the local NED coordinate system.

    NED = North, East, Down

    Therefore:

        X = North
        Y = East
        Z = Down

    DJI gimbal angles are interpreted as:

        yaw:
            horizontal rotation, measured clockwise from North.

        pitch:
            0 degrees  = horizontal
            -90 degrees = looking straight down

        roll:
            rotation around the optical axis.

    Camera coordinate system:

        X = image right
        Y = image down
        Z = camera forward

    The function first calculates the camera optical axis (forward),
    then constructs the camera right/down axes.

    This is the most important geometric transformation in this script.
    """

    yaw = math.radians(gimbal_yaw_deg)
    pitch = math.radians(gimbal_pitch_deg)
    roll = math.radians(gimbal_roll_deg)

    # ------------------------------------------------------------------
    # 1. Camera optical axis / forward direction
    # ------------------------------------------------------------------
    #
    # NED coordinates:
    #
    #     North = X
    #     East  = Y
    #     Down  = Z
    #
    # At:
    #
    #     yaw = 0
    #     pitch = 0
    #
    # the camera points North.
    #
    # At:
    #
    #     pitch = -90
    #
    # it points Down.
    #
    forward = np.array(
        [
            math.cos(pitch) * math.cos(yaw),
            math.cos(pitch) * math.sin(yaw),
            -math.sin(pitch),
        ],
        dtype=float,
    )

    forward = normalize(forward)

    # ------------------------------------------------------------------
    # 2. Camera right direction before roll
    # ------------------------------------------------------------------
    #
    # For a normal oblique view we can construct a horizontal reference
    # direction using the Down vector.
    #
    # However, at exactly -90 degrees pitch, forward is parallel to Down
    # and the cross product becomes undefined.
    #
    # Therefore the nadir case is handled separately.
    #
    down_world = np.array(
        [0.0, 0.0, 1.0],
        dtype=float,
    )

    horizontal_component = np.linalg.norm(
        np.cross(down_world, forward)
    )

    if horizontal_component < 1e-8:

        # Nadir case.
        #
        # At nadir the yaw determines the orientation of the image.
        #
        # For yaw = 0:
        #
        #     image right = East
        #
        right_zero_roll = np.array(
            [
                -math.sin(yaw),
                math.cos(yaw),
                0.0,
            ],
            dtype=float,
        )

    else:

        right_zero_roll = normalize(
            np.cross(
                down_world,
                forward,
            )
        )

    # ------------------------------------------------------------------
    # 3. Camera down direction before roll
    # ------------------------------------------------------------------
    #
    # Cross product gives an orthogonal vector:
    #
    #     forward × right = down
    #
    down_zero_roll = normalize(
        np.cross(
            forward,
            right_zero_roll,
        )
    )

    # ------------------------------------------------------------------
    # 4. Apply camera roll
    # ------------------------------------------------------------------
    #
    # Roll rotates the camera's right/down axes around the optical axis.
    #
    # The optical axis itself does not change.
    #
    right = (
        right_zero_roll * math.cos(roll)
        +
        down_zero_roll * math.sin(roll)
    )

    down = (
        -right_zero_roll * math.sin(roll)
        +
        down_zero_roll * math.cos(roll)
    )

    right = normalize(right)
    down = normalize(down)

    # ------------------------------------------------------------------
    # 5. Combine camera ray components
    # ------------------------------------------------------------------
    #
    # ray_camera:
    #
    #     X = right
    #     Y = down
    #     Z = forward
    #
    ray_ned = (
        ray_camera[0] * right
        +
        ray_camera[1] * down
        +
        ray_camera[2] * forward
    )

    return normalize(ray_ned)


# ============================================================================
# NED -> LOCAL METRIC COORDINATES
# ============================================================================

def ned_to_enu(
    vector_ned: np.ndarray,
) -> np.ndarray:
    """
    Convert a vector from NED to ENU.

    NED:

        [North, East, Down]

    ENU:

        [East, North, Up]

    Therefore:

        east  = north/east swap
        north = NED north
        up    = -NED down
    """

    north = vector_ned[0]
    east = vector_ned[1]
    down = vector_ned[2]

    return np.array(
        [
            east,
            north,
            -down,
        ],
        dtype=float,
    )


# ============================================================================
# FLAT TERRAIN INTERSECTION
# ============================================================================

def intersect_flat_ground(
    camera_x: float,
    camera_y: float,
    camera_z: float,
    ray_enu: np.ndarray,
) -> tuple[float, float, float] | None:
    """
    Intersect a camera ray with a horizontal ground plane.

    Local ENU coordinates:

        X = East
        Y = North
        Z = Up

    The ground plane is:

        Z = 0

    The camera is at:

        (camera_x, camera_y, camera_z)

    The ray is:

        P(t) = camera + t * ray

    Therefore:

        Z(t) = camera_z + t * ray_z

    For the ground:

        Z(t) = 0

    giving:

                 -camera_z
        t = -----------------
                  ray_z

    A valid ground intersection requires:

        ray_z < 0

    because the camera ray must point downward.

    Returns
    -------
    (x, y, t)
        Ground position and ray distance.

    None
        If the ray does not intersect the ground plane.
    """

    ray_z = ray_enu[2]

    # Ray is horizontal or pointing upward.
    if ray_z >= 0:
        return None

    t = -camera_z / ray_z

    if t <= 0:
        return None

    ground_x = camera_x + t * ray_enu[0]
    ground_y = camera_y + t * ray_enu[1]

    return ground_x, ground_y, t


# ============================================================================
# METADATA
# ============================================================================

def metadata_by_filename(
    metadata_rows: list[dict[str, str]],
) -> dict[str, dict[str, str]]:
    """
    Index metadata by image filename stem.

    Example:

        DJI_20260904133936_0015_D.JPG

    becomes:

        DJI_20260904133936_0015_D
    """

    result = {}

    for row in metadata_rows:

        filename = row.get("FileName", "").strip()

        if not filename:
            continue

        stem = Path(filename).stem

        result[stem] = row

    return result


def get_image_size(
    metadata: dict[str, str],
) -> tuple[int, int]:
    """
    Get image dimensions from the metadata.

    Falls back to the known Air 3S image dimensions if necessary.
    """

    width = int(
        float(
            metadata.get(
                "ExifImageWidth",
                DEFAULT_IMAGE_WIDTH,
            )
        )
    )

    height = int(
        float(
            metadata.get(
                "ExifImageHeight",
                DEFAULT_IMAGE_HEIGHT,
            )
        )
    )

    return width, height


# ============================================================================
# GEOJSON
# ============================================================================

def create_feature(
    *,
    image_stem: str,
    object_id: int,
    annotation: dict[str, float],
    pixel_x: float,
    pixel_y: float,
    metric_x: float,
    metric_y: float,
    longitude: float,
    latitude: float,
    ray_distance_m: float,
    ray_ned: np.ndarray,
    metadata: dict[str, str],
) -> dict[str, Any]:
    """
    Create one GeoJSON Point feature.
    """

    return {
        "type": "Feature",

        "geometry": {
            "type": "Point",
            "coordinates": [
                longitude,
                latitude,
            ],
        },

        "properties": {

            # ----------------------------------------------------------
            # Identification
            # ----------------------------------------------------------

            "image": image_stem,
            "object_id": object_id,
            "class_id": int(annotation["class_id"]),

            # ----------------------------------------------------------
            # Image position
            # ----------------------------------------------------------

            "pixel_x": round(pixel_x, 3),
            "pixel_y": round(pixel_y, 3),

            # ----------------------------------------------------------
            # Estimated geographic position
            # ----------------------------------------------------------

            "longitude": longitude,
            "latitude": latitude,

            # ----------------------------------------------------------
            # Metric position
            # ----------------------------------------------------------

            "crs": METRIC_CRS,
            "easting_m": round(metric_x, 3),
            "northing_m": round(metric_y, 3),

            # ----------------------------------------------------------
            # Geometric information
            # ----------------------------------------------------------

            "ray_distance_m": round(
                ray_distance_m,
                3,
            ),

            "ray_north": round(
                float(ray_ned[0]),
                6,
            ),

            "ray_east": round(
                float(ray_ned[1]),
                6,
            ),

            "ray_down": round(
                float(ray_ned[2]),
                6,
            ),

            # ----------------------------------------------------------
            # Drone/camera information
            # ----------------------------------------------------------

            "gps_latitude": parse_float(
                metadata.get("GPSLatitude")
            ),

            "gps_longitude": parse_float(
                metadata.get("GPSLongitude")
            ),

            "relative_altitude_m": parse_float(
                metadata.get("RelativeAltitude")
            ),

            "absolute_altitude_m": parse_float(
                metadata.get("AbsoluteAltitude")
            ),

            "gimbal_pitch_deg": parse_float(
                metadata.get("GimbalPitchDegree")
            ),

            "gimbal_yaw_deg": parse_float(
                metadata.get("GimbalYawDegree")
            ),

            "gimbal_roll_deg": parse_float(
                metadata.get("GimbalRollDegree")
            ),

            "fov_deg": parse_float(
                metadata.get("FOV")
            ),
        },
    }


# ============================================================================
# MAIN
# ============================================================================

def main() -> None:

    print("Loading metadata...")

    metadata_rows = read_csv(METADATA_FILE)

    metadata_index = metadata_by_filename(
        metadata_rows
    )

    print(
        f"Metadata records: {len(metadata_rows)}"
    )

    print(
        f"Annotation directory: {ANNOTATIONS_DIR}"
    )

    annotation_files = sorted(
        ANNOTATIONS_DIR.glob("*.txt")
    )

    print(
        f"Annotation files: {len(annotation_files)}"
    )

    features = []

    # ========================================================================
    # Process every annotated image
    # ========================================================================

    for annotation_file in annotation_files:

        image_stem = annotation_file.stem

        if image_stem not in metadata_index:

            print(
                f"WARNING: metadata not found for "
                f"{image_stem}"
            )

            continue

        metadata = metadata_index[image_stem]

        # --------------------------------------------------------------------
        # Image dimensions
        # --------------------------------------------------------------------

        image_width, image_height = get_image_size(
            metadata
        )

        # --------------------------------------------------------------------
        # Camera field of view
        # --------------------------------------------------------------------

        horizontal_fov_deg = parse_float(
            metadata.get("FOV")
        )

        if horizontal_fov_deg is None:

            raise ValueError(
                f"FOV missing for {image_stem}"
            )

        # Horizontal focal length.
        fx = focal_length_pixels(
            image_width,
            horizontal_fov_deg,
        )

        # We assume square pixels.
        #
        # Therefore:
        #
        #     fx ≈ fy
        #
        # This is a first-order camera model.
        fy = fx

        # --------------------------------------------------------------------
        # Gimbal orientation
        # --------------------------------------------------------------------

        yaw = parse_float(
            metadata.get("GimbalYawDegree")
        )

        pitch = parse_float(
            metadata.get("GimbalPitchDegree")
        )

        roll = parse_float(
            metadata.get("GimbalRollDegree")
        )

        if yaw is None or pitch is None or roll is None:

            print(
                f"WARNING: incomplete gimbal orientation "
                f"for {image_stem}"
            )

            continue

        # --------------------------------------------------------------------
        # Drone geographic position
        # --------------------------------------------------------------------

        drone_lat = parse_float(
            metadata.get("GPSLatitude")
        )

        drone_lon = parse_float(
            metadata.get("GPSLongitude")
        )

        relative_altitude = parse_float(
            metadata.get("RelativeAltitude")
        )

        if (
            drone_lat is None
            or drone_lon is None
            or relative_altitude is None
        ):

            print(
                f"WARNING: incomplete GPS/altitude "
                f"information for {image_stem}"
            )

            continue

        # --------------------------------------------------------------------
        # Drone position in EPSG:29192
        # --------------------------------------------------------------------
        #
        # Input:
        #
        #     longitude, latitude
        #
        # Output:
        #
        #     easting, northing
        #
        # Units:
        #
        #     metres
        #
        drone_x, drone_y = WGS84_TO_METRIC.transform(
            drone_lon,
            drone_lat,
        )

        # --------------------------------------------------------------------
        # Camera height
        # --------------------------------------------------------------------
        #
        # For this first flat model we use RelativeAltitude directly.
        #
        # This means that the local horizontal ground plane is defined as:
        #
        #     Z = 0
        #
        # and the camera is:
        #
        #     Z = RelativeAltitude
        #
        # DEM/elevation correction will be added later.
        camera_z = relative_altitude

        # --------------------------------------------------------------------
        # Read YOLO objects
        # --------------------------------------------------------------------

        annotations = read_yolo_annotations(
            annotation_file
        )

        print(
            f"\n{image_stem}: "
            f"{len(annotations)} cattle"
        )

        # ====================================================================
        # Process each cattle annotation
        # ====================================================================

        for object_id, annotation in enumerate(
            annotations,
            start=1,
        ):

            # ---------------------------------------------------------------
            # 1. YOLO -> pixel coordinates
            # ---------------------------------------------------------------

            pixel_x, pixel_y = yolo_to_pixel(
                annotation,
                image_width,
                image_height,
            )

            # ---------------------------------------------------------------
            # 2. Pixel -> camera ray
            # ---------------------------------------------------------------

            ray_camera = pixel_to_camera_ray(
                pixel_x,
                pixel_y,
                image_width,
                image_height,
                fx,
                fy,
            )

            # ---------------------------------------------------------------
            # 3. Camera ray -> NED
            # ---------------------------------------------------------------

            ray_ned = camera_ray_to_ned(
                ray_camera,
                yaw,
                pitch,
                roll,
            )

            # ---------------------------------------------------------------
            # 4. NED -> ENU
            # ---------------------------------------------------------------

            ray_enu = ned_to_enu(
                ray_ned
            )

            # ---------------------------------------------------------------
            # 5. Ray -> flat ground
            # ---------------------------------------------------------------

            intersection = intersect_flat_ground(
                drone_x,
                drone_y,
                camera_z,
                ray_enu,
            )

            if intersection is None:

                print(
                    f"  Object {object_id}: "
                    f"no ground intersection"
                )

                continue

            ground_x, ground_y, ray_distance = (
                intersection
            )

            # ---------------------------------------------------------------
            # 6. EPSG:29192 -> EPSG:4326
            # ---------------------------------------------------------------
            #
            # The geometric calculation is performed in metres.
            #
            # Only the final result is converted to longitude/latitude.
            #

            longitude, latitude = (
                METRIC_TO_WGS84.transform(
                    ground_x,
                    ground_y,
                )
            )

            # ---------------------------------------------------------------
            # 7. Create GeoJSON feature
            # ---------------------------------------------------------------

            feature = create_feature(
                image_stem=image_stem,
                object_id=object_id,
                annotation=annotation,
                pixel_x=pixel_x,
                pixel_y=pixel_y,
                metric_x=ground_x,
                metric_y=ground_y,
                longitude=longitude,
                latitude=latitude,
                ray_distance_m=ray_distance,
                ray_ned=ray_ned,
                metadata=metadata,
            )

            features.append(feature)

            print(
                f"  Object {object_id}: "
                f"pixel=({pixel_x:.1f}, {pixel_y:.1f}) "
                f"-> "
                f"lon={longitude:.7f}, "
                f"lat={latitude:.7f}"
            )

    # =========================================================================
    # Write GeoJSON
    # =========================================================================

    output = {
        "type": "FeatureCollection",

        "name": "cattle_locations_flat",

        "crs": {
            "type": "name",
            "properties": {
                "name": GEOGRAPHIC_CRS,
            },
        },

        "properties": {
            "method": "flat_terrain",
            "metric_crs": METRIC_CRS,
            "geographic_crs": GEOGRAPHIC_CRS,
            "description": (
                "Cattle positions estimated from "
                "YOLO bounding-box centers and "
                "drone camera geometry assuming "
                "a horizontal ground plane."
            ),
        },

        "features": features,
    }

    OUTPUT_FILE.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with OUTPUT_FILE.open(
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            output,
            f,
            indent=2,
            ensure_ascii=False,
        )

    print()
    print("=" * 70)
    print("Flat geolocation completed.")
    print(f"Objects: {len(features)}")
    print(f"Output : {OUTPUT_FILE}")
    print("=" * 70)


